"""
مولّد عقود الوقف والتمويل الإلكترونية وشهادات الوقف الرقمية
صياغة قانونية متكاملة مطابقة لأحكام قانون الأوقاف الجزائري رقم 25-06
"""
from datetime import datetime
import uuid
from typing import List, Dict
from app.config import settings, WAQF_CATEGORIES, ISLAMIC_FINANCING_FORMULAS

class ContractGenerator:
    @staticmethod
    def generate_waqf_contract(
        waqif_name: str,
        waqif_id_number: str,
        waqif_address: str,
        waqf_title: str,
        waqf_code: str,
        amount: float,
        waqf_type: str, # PERPETUAL أو TEMPORARY
        temporary_months: int = None,
        temporary_destination: str = None,
        conditions: List[Dict] = None,
        risk_preference: str = "CONSERVATIVE"
    ) -> Dict[str, str]:
        """
        توليد نص عقد الوقف الإلكتروني المحرر وفق القانون 25-06
        """
        contract_number = f"WQF-CTR-DZ-{datetime.utcnow().year}-{uuid.uuid4().hex[:8].upper()}"
        certificate_code = f"CERT-WAQF-{uuid.uuid4().hex[:10].upper()}"
        
        waqf_type_text = "وقف مؤبد دائم إلى أن يرث الله الأرض ومن عليها" if waqf_type == "PERPETUAL" else f"وقف مؤقت محدد بمدة ({temporary_months} شهراً)، ويؤول أصل المال بعد انقضائها إلى: {temporary_destination or 'الواقف أو ورثته الشرعيين'}"
        
        categories_text = ""
        if conditions:
            for c in conditions:
                cat_name = WAQF_CATEGORIES.get(c.get("category_id"), {}).get("name", c.get("category_id"))
                pct = c.get("percentage", 100)
                add_cond = c.get("additional_conditions") or "حسب الاحتياج الأشد"
                categories_text += f"- {cat_name}: بنسبة ({pct}%) | الشرط المقيد: {add_cond}\n"
        else:
            categories_text = "- وقف لخدمة المجتمع بنسبة 100% في وجوه البر العامة.\n"

        contract_ar = f"""
========================================================================================
                          الجمهورية الجزائرية الديمقراطية الشعبية
                      عقد إنشاء وقف نقدي استثماري إلكتروني موثق
    محرر وفق أحكام القانون رقم 25-06 المؤرخ في 23 محرم عام 1447هـ الموافق 19 يوليو 2025م
         المتعلق بالأوقاف (المنشور بالجريدة الرسمية للجمهورية الجزائرية رقم 47)
========================================================================================

رقم العقد الرسمي: {contract_number}
تاريخ التحرير: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}
رمز المحفظة الوقفية المستقلة: {waqf_code}

الحمد لله وحده والصلاة والسلام على من لا نبي بعده، أما بعد:

فإنه بتاريخه وساعته، انعقد هذا العقد والتراضي التام بين كل من:

الطرف الأول (الواقف):
الاسم واللقب: {waqif_name}
رقم بطاقة الهوية / جواز السفر: {waqif_id_number}
العنوان والموطن المختار: {waqif_address}
(ويشار إليه لاحقاً بـ "الواقف")

الطرف الثاني (الناظر):
{settings.PLATFORM_NAME} - بصفتها المشغّل القانوني والناظر المعتمد على الأوقاف النقدية الاستثمارية
المقر الاجتماعي: الجزائر العاصمة، الجمهورية الجزائرية الديمقراطية الشعبية
(ويشار إليها لاحقاً بـ "الناظر" أو "المنصة")

                                   تمهيد
حيث إن الواقف يرغب في حبس مال نقدي تقرباً إلى الله تعالى وتحقيقاً لمقاصد البر والتكافل الاجتماعي،
وانطلاقاً من المادة 15 من القانون رقم 25-06 التي تنص صراحة على أن المال الموقوف يكون إما عقاراً أو منقولاً أو نقوداً،
وحيث إن المنصة تتولى نظارة هذا الوقف وإدارته واستثماره وفقاً للمادتين 64 و 65 من ذات القانون،
فقد اتفق الطرفان، وهما بكامل الأهلية المعتبرة شرعاً وقانوناً، على البنود الآتية:

البند الأول: موضوع الوقف ومبلغه
وقف الواقف طائعاً مختاراً من خالص ماله الحلال مبلغاً نقدياً قدره:
({amount:,.2f} {settings.CURRENCY_AR}) - فقط {amount:,.2f} دينار جزائري.
وقد أقر الواقف بخلو هذا المال من أي شبهة أو نزاع ومطابقته للتشريع المتعلق بالوقاية من تبييض الأموال ومكافحته (القانون 05-01).

البند الثاني: طبيعة الوقف واستقلالية الذمة
يكتسب هذا الوقف الشخصية المعنوية المستقلة بمجرد إنشائه عملاً بأحكام المادة 31 من القانون 25-06.
ويكون لهذا الوقف حساب مستقل وسجلات محاسبية مفصولة تماماً عن حسابات المنصة الخاصة وعن سائر الأوقاف الأخرى.
صفة هذا الوقف: {waqf_type_text} (عملاً بأحكام المادتين 22 و 54 من القانون 25-06).

البند الثالث: صيانة أصل الوقف واستثماره بدون ضمان لرأس المال
1. عملاً بالمادة 33 من القانون 25-06، لا يجوز لأي كان التصرف في أصل هذا الملك الوقفي بالبيع أو الهبة أو الإرث أو التنازل، بل يبقى أصل المال محبّساً ومصوناً.
2. يفوّض الواقفُ المنصةَ كناظر في استثمار أصل المال في مشاريع تنموية مباحة ومتوافقة مع الشريعة الإسلامية بالصيغ السبع المعتمدة (المشاركة، المضاربة، المرابحة، السلم، الاستصناع، الإجارة، المزارعة).
3. يقر الواقف بعلمه التام وإقراره بأن الاستثمار في الشريعة الإسلامية يقوم على الغنم بالغرم وتوزيع المخاطر، ولا يوجد فيه ضمان لرأس المال ضد الخسارة الناتجة عن تقلبات السوق الطبيعية دون تعدٍّ أو تفريط.
4. نمط الاستثمار المعتمد لهذا الوقف هو: النمط ({risk_preference}).

البند الرابع: شرط الوقف ومصارف الأرباح (الجهات المستفيدة)
1. يُصرف ريع هذا الوقف وعوائده الاستثمارية فقط وحصراً على الجهات والأوجه المحددة أدناه وفق شرط الواقف (المادتان 18 و 20 من القانون):
{categories_text}
2. لا يُصرف من أصل رأس المال درهم واحد، وتصرف الأرباح دورياً بعد اعتماد القوائم المالية.

البند الخامس: أجرة الناظر وصندوق الاحتياطي
1. تستحق المنصة (الناظر) عملاً بعقد النظارة ومقررات الهيئة الشرعية أجرة ناظر نسبتها ({settings.DEFAULT_NAZIR_FEE_PERCENTAGE}%) فقط من صافي الأرباح الاستثمارية المحققة فعلياً.
2. يُستقطع نسبة ({settings.DEFAULT_RESERVE_FUND_PERCENTAGE}%) من العوائد توجه لصالح "صندوق احتياطي الأوقاف" لدعم استقرار الوقف ومواجهة المخاطر المحتملة (المادة 86).

البند السادس: معالجة تعذر شرط الوقف (نظرية الاستبدال)
إذا طرأ تعذر على صرف الريع في الجهة المحددة لزوالها أو انقطاعها، يفوّض الواقفُ الناظرَ والهيئةَ الشرعية في تحويل الريع إلى أقرب جهة أو مشروع خيري مماثل ضمن نفس الفئة الوقعية، عملاً بأحكام المادة 35 من القانون 25-06، مع إشعار الواقف بذلك فورياً.

البند السابع: فترة المراجعة والتراجع (72 ساعة)
يمنح القانون والنظام الداخلي للواقف مهلة تراجع كاملة مدتها (72 ساعة) ابتداءً من لحظة توقيع هذا العقد؛ يحق له خلالها إلغاء العملية واسترداد كامل المبلغ إلى حسابه البنكي. وبانقضاء هذه المهلة يصبح الوقف لازماً ونهائياً وناجزاً عملاً بأحكام المادة 19 من القانون 25-06.

البند الثامن: التوقيع الإلكتروني والحجية القانونية
أقر الواقف باطلاعه وفهمه الكامل لكافة بنود هذا العقد وسياسة المخاطر، ووقع عليه إلكترونياً عبر المنصة بالبصمة الرقمية المعتمدة.

========================================================================================
الواقف (توقيع إلكتروني مصادق عليه)           الناظر: {settings.PLATFORM_NAME}
الاسم: {waqif_name}                         التوقيع والختم الرقمي للمنصة
رمز الشهادة الوقفية: {certificate_code}       سجل تجاري وترخيص رسمي معتمد
========================================================================================
"""
        return {
            "contract_number": contract_number,
            "certificate_code": certificate_code,
            "contract_text": contract_ar.strip()
        }

    @staticmethod
    def generate_funding_contract(
        funder_name: str,
        project_title: str,
        sector: str,
        islamic_formula: str,
        amount: float,
        agreed_profit_pct: float,
        escrow_account: str
    ) -> Dict[str, str]:
        """
        عقد تمويل استثماري بصيغة إسلامية
        """
        contract_number = f"FND-CTR-DZ-{datetime.utcnow().year}-{uuid.uuid4().hex[:8].upper()}"
        
        formula_info = ISLAMIC_FINANCING_FORMULAS.get(islamic_formula, {})
        formula_name = formula_info.get("name", islamic_formula)
        legal_art = formula_info.get("legal_article", "قانون الأوقاف 25-06")

        contract_ar = f"""
========================================================================================
                          عقد تمويل استثماري بصيغة ({formula_name})
              وفقاً لأحكام القانون رقم 25-06 المنظم للأوقاف والاستثمارات الإسلامية
========================================================================================
رقم العقد: {contract_number}
تاريخ العقد: {datetime.utcnow().strftime('%Y-%m-%d')}
حساب الضمان المستقل (Escrow): {escrow_account}

أطراف العقد:
الطرف الأول (الممول/المستثمر): {funder_name}
الطرف الثاني: {settings.PLATFORM_NAME} كجهة ناظرة ووسيطة ومشرفة على حساب الضمان.

موضوع العقد:
تمويل مشروع: "{project_title}" بالقطاع: ({sector})
المبلغ الملتزم به: {amount:,.2f} {settings.CURRENCY_AR}
الصيغة الشرعية: {formula_name} استناداً إلى {legal_art}.

الشروط الجوهرية:
1. نسبة اقتسام الأرباح المتفق عليها: للممول ({agreed_profit_pct}%) من ربح المشروع الفعلي.
2. لا يوجد أي ضمان لرأس المال ضد الخسائر التجارية العادية غير الناشئة عن التعدي أو التقصير.
3. تودع أموال التمويل في حساب الضمان المنفصل، ولا تسلم نقداً بل تصرف على دفعات مرتبطة بمراحل الإنجاز المتحقق منها ميدانياً.
4. يلتزم الطرفان بأحكام الهيئة الشرعية والتدقيق المالي المستقل.
========================================================================================
"""
        return {
            "contract_number": contract_number,
            "contract_text": contract_ar.strip()
        }
